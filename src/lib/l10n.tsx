const dicts: Record<Lang, Dict> = { en, hi, mr };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

type LangCtx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string };

const LangContext = createContext<LangCtx>({
  lang: "en",
  setLang: () => {},
  t: (key, vars) => translate("en", key, vars),
});

const LANG_KEY = "sunrich_lang";

export function LanguageProvider({
  initialLang,
  onPersist,
  children,
}: {
  initialLang?: Lang | null;
  onPersist?: (lang: Lang) => void;
  children: ReactNode;
}) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "en";
    const stored = window.localStorage.getItem(LANG_KEY) as Lang | null;
    if (stored === "en" || stored === "hi" || stored === "mr") return stored;
    return initialLang ?? "en";
  });

  // The language picked on this device (login screen chips) wins over the saved
  // profile language; when they differ, push the device choice to the profile.
  useEffect(() => {
    if (!initialLang) return;
    let stored: string | null = null;
    try {
      stored = window.localStorage.getItem(LANG_KEY);
    } catch {
      stored = null;
    }
    if (stored === "en" || stored === "hi" || stored === "mr") {
      setLangState(stored);
      if (stored !== initialLang) onPersist?.(stored);
    } else {
      setLangState(initialLang);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initialLang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(LANG_KEY, l);
    } catch {
      // storage unavailable — language is per-session only
    }
    onPersist?.(l);
  };

  const value = useMemo<LangCtx>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    // setLang is a fresh closure each render (it captures onPersist); including it
    // keeps the context from freezing the first render's onPersist (stale staff).
    [lang, setLang],
  );
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
